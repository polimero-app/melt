#!/usr/bin/env python3
"""Update the Homebrew cask from published GitHub release API metadata."""

import argparse
import json
import re
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "Casks/melt.rb"
RELEASE_URL = "https://github.com/polimero-app/melt/releases/download"


def render_cask(release):
    if release.get("draft", True):
        raise ValueError("Homebrew requires a published release")
    tag = release["tag_name"]
    if not re.fullmatch(r"\d{4}\.\d{2}\.\d{2}(?:\.\d+)?", tag):
        raise ValueError(f"Expected a dated nightly release tag, got {tag!r}")

    installers = {}
    for asset in release["assets"]:
        match = re.fullmatch(r"Melt_(\d+\.\d+\.\d+)_(aarch64|x86_64)\.dmg", asset["name"])
        if not match:
            continue
        package_version, arch = match.groups()
        if arch in installers:
            raise ValueError(f"Duplicate macOS installer for {arch}")
        expected_url = f"{RELEASE_URL}/{tag}/{asset['name']}"
        if asset["browser_download_url"] != expected_url:
            raise ValueError(f"Unexpected download URL for {arch}")
        digest = asset.get("digest") or ""
        if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
            raise ValueError(f"Missing or invalid SHA-256 digest for {arch}")
        installers[arch] = (package_version, digest.removeprefix("sha256:"))

    if set(installers) != {"aarch64", "x86_64"}:
        raise ValueError("Both Apple Silicon and Intel DMGs are required")
    package_version, arm_sha = installers["aarch64"]
    intel_version, intel_sha = installers["x86_64"]
    expected_version = ".".join(str(int(part)) for part in tag.split(".")[:3])
    if package_version != expected_version or intel_version != expected_version:
        raise ValueError("Installer versions must match the nightly release date")

    return f'''# Generated by scripts/update_homebrew_cask.py; do not edit release metadata by hand.
cask "melt" do
  arch arm: "aarch64", intel: "x86_64"

  version "{tag}"
  sha256 arm:   "{arm_sha}",
         intel: "{intel_sha}"

  on_arm do
    depends_on formula: "openssl@4"
  end
  on_intel do
    depends_on formula: "openssl@3"
  end

  url "{RELEASE_URL}/#{{version}}/Melt_{package_version}_#{{arch}}.dmg"
  name "Melt"
  desc "Local-first 3D printer control"
  homepage "https://melt.polimero.app/"

  depends_on :macos

  app "Melt.app"
  binary "#{{appdir}}/Melt.app/Contents/MacOS/melt"
end
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("release_json", type=Path, help="JSON from gh api repos/polimero-app/melt/releases/tags/<tag>")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    try:
        content = render_cask(json.loads(args.release_json.read_text()))
    except (KeyError, TypeError, ValueError) as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content)
    print(f"Updated {args.output}")


if __name__ == "__main__":
    main()
